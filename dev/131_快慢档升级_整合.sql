-- dev/135：战备任务线的任务经验**不享受**「勤学苦练」快档加成 —— 2026-09-26
-- ===============================================================
-- 起因（站长定稿）：快档（3 倍经验）**包括任务经验**，但**不包括战备任务**。
--
-- 为什么必须排除：战备线最后一步「实战训练：<职业>」（90140-90148 / 90150-90158）的
--   `RewMoneyMaxLevel = 1800000`、`QuestLevel = 50`，而任务经验 = `Quest::XPValue()`
--   （Quests/QuestDef.cpp:176-214，QL<=60 时 `fullxp = RewMoneyMaxLevel / 0.6`）
--   ⇒ 单次 **3,000,000 XP**。若再乘 3 倍就是 9,000,000，直接冲穿整个 60-70 段。
--
-- 实现：新增一个**可由 DB 指定的任务特殊标志** `QUEST_SPECIAL_FLAG_NO_XP_BONUS = 0x080`（|128）
--   · Quests/QuestDef.h：加枚举 + 并进 `QUEST_SPECIAL_FLAG_DB_ALLOWED`
--     （ObjectMgr.cpp:4725 会校验 `m_SpecialFlags > QUEST_SPECIAL_FLAG_DB_ALLOWED`，不加会被拒）
--   · Entities/Player.h / Player.cpp：`GiveXP()` 增加第 4 个参数 `ignoreXpBonus`
--     —— 该参数为真时**跳过** `SPELL_AURA_MOD_XP_PCT` 光环的乘法（Player.cpp:2760 那段）
--   · Player.cpp `Player::RewardQuest` 的任务经验分支：
--       `GiveXP(xp, nullptr, 1.0f, pQuest->HasSpecialFlag(QUEST_SPECIAL_FLAG_NO_XP_BONUS));`
--   ⇒ 杀怪/探索经验照旧吃满 3 倍，只有带这个标志的任务不吃。
--
-- ⚠️ 为什么不用"把 RewMoneyMaxLevel 改成 1/3"这种纯 SQL 办法：那个值同时决定
--    满级后 XP→金币的折算，改了会让满级玩家的金币也变成 1/3 ✗。
--
-- 影响面：只动这 18 条任务的 SpecialFlags 一个 bit，其余字段不动；幂等（带 `& 128 = 0` 守卫）。
-- 执行对象：world 库（tbcmangos，表名不加库前缀）
-- ===============================================================

