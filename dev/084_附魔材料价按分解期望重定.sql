-- 084_附魔材料价按分解期望重定.sql（2026-09-18）
--
-- 站长报的问题：**拍卖行买装备 → 分解 → 卖附魔材料** 这条套利空间很大。
--
-- ── 量化（云端实测，见 /root/de_arbitrage.py）──
--   · 拍卖行里 bot 在卖的可分解装备 **3,452 种**，其中 **2,847 种（82%）的分解期望价值高于售价**；
--     最高 +841%（例：`15931 奥术之星` 售价 1.01 金 / 分解值 9.52 金）；
--   · 蓝装挂单最低 **0.04 金**、紫装最低 **3.40 金**，而分解出的
--     大块棱光碎片 10.80 金 / 虚空水晶 25.00 金 → 差额就是套利空间；
--   · bot 光是"大块棱光碎片"一项就吃下 1218 个、付出 **11,394 金**（累计净投放 11,905 金）。
--
-- ── 定价方法（站长定案：以方案1为主，材料价适当留高）──
--   把「装备售价 P_i ≥ Σ(分解产出 x_ij × 材料价 p_j) × (1/relax)」当作约束，
--   从当前材料价出发迭代收缩（Gauss-Seidel），直到"分解利润"落在合理区间：
--     · relax = **1.5** → 允许最多 50% 的分解利润（合法的专业收益），不允许更多；
--     · 地板 = **原价的 15%**（站长定的"适当高一点"）：任何材料不跌破原价 15%，
--       也绝不低于卖店价 —— 避免低级材料被压成 0（取消地板会让 强效星界精华/大块微光碎片/灵魂之尘
--       掉到 0.01~0 金，属畸形值）。
--
-- ── 效果（relax 1.5 + 15% 地板，见 /root/de_final2.py）──
--   可套利装备：2,847 件 → 约 700 件；其中 >50% 利润的仅 **4 件**（原方案是 2,847 件）；
--   档位对照（地板 30% / 15% / 无）：
--       地板30%：>1.1倍 285 件 / >1.3倍 156 件 / >1.5倍 63 件
--       地板15%：>1.1倍 137 件 / >1.3倍  45 件 / >1.5倍  4 件   ← 本文件采用
--       无地板 ：>1.1倍 124 件 / >1.3倍  43 件 / >1.5倍  0 件（代价：3 项低级材料近乎白送）
--
-- ── 生效方式 ──
--   `ahbot_market_state.price_ref` 是 bot 的**钉价**（category 1 + price_ref>0），启动时载入
--   （`AuctionHouseBot::LoadCatalogOverrides`）→ **需重启 mangosd**。
--
-- 幂等：全部是"绝对赋值"，重复执行结果一致。备份表保存改前值，可一键回滚。
-- 回滚：UPDATE ahbot_market_state m JOIN ahbot_market_state_bak_20260918_ench b ON b.item=m.item
--         SET m.price_ref = b.price_ref;
-- ============================================================================

