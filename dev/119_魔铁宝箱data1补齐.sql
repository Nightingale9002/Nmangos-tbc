--
-- 幂等：`AND data1 <> 1081798` 守卫 ⇒ 第二次执行 0 行；已经是对的库（本地）执行 0 行。
-- 生效：gameobject_template 启动时载入 ⇒ 需重启（云端每日 03:00 自动重启）。
-- 回滚：`dev/rollback/119_回滚_魔铁宝箱data1.sql`（还原为云端原值 9933）
-- ===============================================================

