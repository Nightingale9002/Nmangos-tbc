-- ===============================================================
-- 背景：dev/117 给 39 个箱子各建专属掉落模板（entry = 900000 + GO），并把箱子 GO 的 data1 指向新模板。
--   其中 GO 181798（魔铁宝箱 / Fel Iron Chest）那条 UPDATE 带"旧值守卫" `AND data1 = 21278`，
