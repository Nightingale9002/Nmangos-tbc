-- Character database. Generic positioning rules; no seed bindings are enabled here.
-- Idempotent schema only; re-running preserves operator-tuned values.
CREATE TABLE IF NOT EXISTS ai_playerbot_spread_rule (
  map INT UNSIGNED NOT NULL,
  boss_entry INT UNSIGNED NOT NULL,
  enabled TINYINT UNSIGNED NOT NULL DEFAULT 0,
  layout VARCHAR(8) NOT NULL DEFAULT 'ring',
  distance_mode TINYINT UNSIGNED NOT NULL DEFAULT 1,
  angular_mode TINYINT UNSIGNED NOT NULL DEFAULT 0,
  radius_min FLOAT NOT NULL DEFAULT 0,
  radius_max FLOAT NOT NULL DEFAULT 40,
  preferred_radius FLOAT NOT NULL DEFAULT 20,
  min_separation FLOAT NOT NULL DEFAULT 10,
  bounce_distance FLOAT NOT NULL DEFAULT 8,
  cone_angle_deg FLOAT NOT NULL DEFAULT 0,
  cone_range FLOAT NOT NULL DEFAULT 0,
  max_affected INT UNSIGNED NOT NULL DEFAULT 1,
  pair_distance_max FLOAT NOT NULL DEFAULT 0,
  move_role_mask INT UNSIGNED NOT NULL DEFAULT 28,
  count_role_mask INT UNSIGNED NOT NULL DEFAULT 28,
  pair_los TINYINT UNSIGNED NOT NULL DEFAULT 0,
  arrival_tolerance FLOAT NOT NULL DEFAULT 0.5,
  replan_distance FLOAT NOT NULL DEFAULT 3,
  sample_step FLOAT NOT NULL DEFAULT 2,
  search_budget INT UNSIGNED NOT NULL DEFAULT 200000,
  center_set TINYINT UNSIGNED NOT NULL DEFAULT 0,
  center_x FLOAT NOT NULL DEFAULT 0,
  center_y FLOAT NOT NULL DEFAULT 0,
  center_z FLOAT NOT NULL DEFAULT 0,
  tank_bearing_deg FLOAT NOT NULL DEFAULT 0,
  boss_tolerance FLOAT NOT NULL DEFAULT 2,
  dps_boss_range_max FLOAT NOT NULL DEFAULT 0,
  healer_member_range_max FLOAT NOT NULL DEFAULT 0,
  PRIMARY KEY(map,boss_entry)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
