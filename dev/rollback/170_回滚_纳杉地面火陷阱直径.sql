UPDATE `tbcmangos`.`gameobject_template`
   SET `data2` = 0
 WHERE `entry` IN (180125, 182533) AND `type` = 6 AND `data2` = 6;

-- ---------- 核对 ----------
SELECT `entry`, `name`, `data1`, `data2`, `data3`
  FROM `tbcmangos`.`gameobject_template`
 WHERE `entry` IN (180125, 182533) ORDER BY `entry`;
