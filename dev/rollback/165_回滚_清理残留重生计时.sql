-- 本文件**无需回滚**，原因：
--   1) 被删的行是"上游 bug（GO_FLAG_NODESPAWN 未生效）导致门/按钮被移出世界"时写下的
--      临时重生计时（值 = 使用时刻 + spawntimesecs），属于垃圾状态；
--   2) 该状态由运行期自动重建：只要门再次被使用、又被移出世界，就会按同一逻辑写回；
--      核心修复（commit `f5ca11d17`）之后不会再产生这类行；
--   3) 若确实要让"被删掉的那几个门"回到旧行为，只需在游戏里再点一次那道门（或等一次
--      服务器重启后由脚本/事件重新驱动），不需要数据回滚。
-- 因此这里只放一条**只读**核对语句，确认当前没有同类未来时间行：
-- =====================================================================================

SELECT COUNT(*) AS 残留行
  FROM `tbccharacters`.`gameobject_respawn` r
  JOIN `tbcmangos`.`gameobject` g          ON g.guid = r.guid
  JOIN `tbcmangos`.`gameobject_template` t ON t.entry = g.id
 WHERE (t.flags & 0x20) AND t.type IN (0, 1) AND r.respawntime > UNIX_TIMESTAMP();
