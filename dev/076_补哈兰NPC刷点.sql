-- 背景：哈兰是 cmangos 的 OutdoorPvP 玩法（src/game/OutdoorPvP/OutdoorPvPNA.cpp，开关 OutdoorPvp.NAEnabled
--       默认开，World.cpp:745）。这个系统**自己不生成 NPC**：源码把卫兵和商人都当 "permanent DB spawns"
--       （守卫的死亡位置取自 creature->GetRespawnCoord()），系统只按占领方做 despawn / Respawn。
