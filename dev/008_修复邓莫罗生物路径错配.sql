-- =====================================================
-- 修复邓莫罗野生动物路径错配（2026-08-14）
--
-- 问题：以下 4 个生物带有 creature_movement 路径，但路径点
-- 全部位于距离出生点 230~1300+ 码的无关区域（其中 3557 的
-- 路径是铁炉堡巡山人 guid 225 的巡逻路线副本），导致怪物
-- 出生后长距离跑图/穿山/浮空。
--
--    guid | entry | 名称            | 出生点               | 路径位置            | 距离
--    -----+-------+-----------------+----------------------+---------------------+-------
--    3557 |  1199 | 幼年雪豹        | -5730,-316 (Z363)    | -5711..-5720,-550..-576 (Z398) | ~234
--    3596 |  1199 | 幼年雪豹        | -5809,-178 (Z352)    | -5675..-5328,-482..-520 (Z391)  | ~332
--    3595 |  1125 | 峭壁野猪        | -5859,-260 (Z360)    | -5907..-6036,31..63 (Z367)      | ~296
--    4360 |  1127 | 老峭壁野猪      | -5810,-1090 (Z383)   | -6241..-6265,162..319 (Z382)    | ~1325
--
-- 修复方式：删除错配路径，改为与同类一致的随机游荡
-- （同类 1199 多为 MovementType=1 spawndist=5；
--   同类 1125 全部为 MovementType=1 spawndist=10；
--   同类 1127 多为 MovementType=1 spawndist=5）。
--
-- 该错误数据在 8/3、8/7 的数据库 dump 中即已存在，属于底层
-- 数据库自带问题，与移动代码修改无关。
-- =====================================================

-- ① 删除错配的路径点（原数据仍保存在 Dump20260807*.sql 等 dump 中，可恢复）
DELETE FROM `creature_movement` WHERE `Id` IN (3557, 3596, 3595, 4360);

-- ② 幼年雪豹（guid 3557、3596）：改为随机游荡，spawndist=5
UPDATE `creature` SET `MovementType` = 1, `spawndist` = 5 WHERE `guid` IN (3557, 3596);

-- ③ 峭壁野猪（guid 3595）：改为随机游荡，spawndist=10
UPDATE `creature` SET `MovementType` = 1, `spawndist` = 10 WHERE `guid` = 3595;

-- ④ 老峭壁野猪（guid 4360）：改为随机游荡，spawndist=5
UPDATE `creature` SET `MovementType` = 1, `spawndist` = 5 WHERE `guid` = 4360;

