-- 本表只放**阈值**与**达标后的权重**；"达标前"的权重在 ai_playerbot_weightscale_data（dev/178）。
--
-- 代码：RandomItemMgr::LoadWeightCaps() / ApplyWeightCap() / GetAvoidanceBasisPoints()
--   cap       = 角色当前该战斗等级达到这个数就算"达标"；cap=0 表示"没有自己的上限，由四维(avoid4)统一门控"
--   capped    = 达标后该属性的权重（单位与 ai_playerbot_weightscale_data 相同；0 = 达标后无收益）
--   alt_field / alt_cap = 备选达标途径（"或"）：熊德免暴 = 防御等级 156 或 韧性 103
--   avoid4 行 = 四维（未命中 + 闪躲 + 招架 + 格挡）总上限，单位万分之一（10240 = 102.4%）
--
-- 站长原文要点：
--   * 防战：免暴 490 防御技能（≈332 防御等级）；精准软上限 26（≈103 等级）、硬上限 56；命中 9%（142 等级）；
--           护甲上限 35880。**"免碾"靠盾牌格挡技能(+75%)，面板四维不是防战的硬性达标线** ⇒ 防战不做四维门控。
--           达标后优先级：耐力 > 防御等级 > 护甲 > 躲闪 > 招架 > 格挡 > 敏捷 > 格挡值 > 命中 > 精准 > 力量
--           ⇒ 防御等级达标后**不降权**（仍是第 2 优先），只降命中/精准。
--   * 防骑：免暴 = 490 防御技能；免碾 = 四维 ≥102.4%（未命中 = 5% + (防御技能-365)×0.04%，格挡含神盾 +30%）；
--           法术命中额外 2%（天赋已给 3%）保"正义防御"不 Miss；格挡值上限 2400（超过收益骤减）。
--           达标后优先级：耐力 > 法术伤害 > 命中 > 精准。
--   * 熊德：免暴 = 156 防御等级 或 103 韧性（站长口径：熊按韧性算）。
--   * 物理 DPS：命中 9% =142、精准 26 =103（打背）；法系：奥法 76 / 冰火法·术士·暗牧 164 / 鸟德 152 / 元素萨 51。
--
-- 幂等：整表重建。执行：mysql -uroot -p tbcmangos < 177_属性上限表_达标降权.sql

