-- 主题：测试假人 —— 被动 + 不转身
-- ----------------------------------------------------------------------------
-- [2026-10-29 站长口径] 假人必须"站着不动、不转身"：
--   `UNIT_FLAG_STUNNED`(0x00040000) 在核心里的注释就是 "turn and strafe movement disabled"
--     （转身/侧移禁用）——这是"目标不会转身"的唯一标准开关；
--   `UNIT_FLAG_PACIFIED`(0x00020000) 让它不主动攻击（被动假人）。
--   两个一起加，近战就能稳定站在背后输出，不会被"目标转身"逼着一直绕圈。
--   MovementType=0（idle）保证它不巡逻、不追人。
--   只改本地测试用的 190013/190014/190015（训练假人三兄弟），与正式内容无关。
--   幂等：位或 + 赋值，可重复执行。
-- ============================================================================

UPDATE creature_template
   SET UnitFlags    = UnitFlags | 0x00040000 | 0x00020000,   -- STUNNED | PACIFIED
       MovementType = 0                                      -- idle
 WHERE entry IN (190013, 190014, 190015);

SELECT entry, name, UnitFlags, MovementType
  FROM creature_template
 WHERE entry IN (190013, 190014, 190015);
